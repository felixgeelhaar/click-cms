import { test, expect } from '@playwright/test';
import { resolve } from 'node:path';
const out = resolve(process.env.CLICK_E2E_SCREENSHOTS || 'test-results/editing-screenshots');
test.skip(process.env.CLICK_E2E !== '1', 'Requires isolated running CMS');
test('draft persists, live preview renders, security loads, mobile fits', async ({ page }) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/admin/');
  await page.locator('#login-username').fill(process.env.CLICK_E2E_USER || 'admin');
  await page.locator('#login-password').fill(process.env.CLICK_E2E_PASS || 'admin-demo-pass-99');
  await page.locator('button[type=submit]').click();
  await expect(page.getByRole('heading', { name: 'Dashboard', exact: true })).toBeVisible();
  await page.goto('/admin/pages/edit/home');
  const title = page.locator('#page-title');
  await expect(title).not.toHaveValue('');
  const original = await title.inputValue();
  await title.fill(`${original} — E2E draft`);
  const save = page.getByRole('button', { name: 'Save', exact: true });
  await save.click();
  await expect(page.getByRole('status').filter({ hasText: 'Saved.' })).toBeVisible();
  await page.reload();
  await expect(title).toHaveValue(`${original} — E2E draft`);
  await title.fill(original);
  await save.click();
  await expect(page.getByRole('status').filter({ hasText: 'Saved.' })).toBeVisible();
  await page.getByRole('button', { name: 'Live preview', exact: true }).click();
  const frame = page.locator('iframe[title="Rendered page preview"]');
  await expect(frame).toBeVisible();
  await expect(page.frameLocator('iframe[title="Rendered page preview"]').locator('h1')).toBeVisible();
  await frame.scrollIntoViewIfNeeded();
  await page.screenshot({ path: `${out}/live-preview.png` });
  await page.goto('/admin/security');
  await expect(page.getByRole('heading', { name: 'Security health', exact: true })).toBeVisible();
  await expect(page.locator('.check-card').first()).toBeVisible();
  await page.screenshot({ path: `${out}/security-health.png`, fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/admin/pages');
  await expect(page.getByRole('heading', { name: 'Pages', exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  await page.screenshot({ path: `${out}/admin-mobile.png`, fullPage: true });
  expect(errors).toEqual([]);
});
test('public theme renders on desktop and mobile', async ({ page }) => {
  await page.goto('/');
  await expect(page.locator('h1')).toBeVisible();
  const style = page.locator('link[rel=stylesheet]');
  const response = await page.request.get(await style.getAttribute('href'));
  expect(response.ok()).toBeTruthy();
  expect(response.headers()['content-type']).toContain('text/css');
  await page.screenshot({ path: `${out}/public-site.png` });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  await page.screenshot({ path: `${out}/public-site-mobile.png` });
});
